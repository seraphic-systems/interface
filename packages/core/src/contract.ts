import { nodeSchemas, referenceType, schemas, type Schema } from './schemas.js';

export const SCHEMA_VERSION = 1;

function inlineCommon(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(inlineCommon);
  if (value === null || typeof value !== 'object') return value;
  let object = { ...value } as Schema;
  if (object.$ref) {
    const ref = object.$ref;
    if (!ref.startsWith('common.schema.json#/$defs/')) throw new Error(`Unsupported public contract reference: ${ref}`);
    delete object.$ref;
    object = { ...structuredClone(schemas['common.schema.json'].$defs![ref.split('/').at(-1)!]), ...object };
  }
  return Object.fromEntries(Object.entries(object).filter(([key]) => key !== 'default').map(([key, item]) => [key, inlineCommon(item)]));
}

export function buildPublicSchema(): Schema {
  const common = schemas['common.schema.json'].$defs!;
  const definitions: Record<string, Schema> = {};
  for (const [name, source] of Object.entries(nodeSchemas)) {
    const fields = { ...structuredClone(common.base.properties!), ...structuredClone(source.properties!) };
    delete fields.visibility;
    if (name === 'Node') {
      fields.properties = { type: 'object', properties: {}, additionalProperties: false };
    } else {
      const props = Object.fromEntries(Object.entries(fields.properties).filter(([key]) => ['type', 'properties', 'required', 'additionalProperties'].includes(key))) as Schema;
      const references = new Set(Object.entries(props.properties!).filter(([, definition]) => referenceType(definition)).map(([key]) => key));
      props.required = (props.required ?? []).filter(key => !references.has(key));
      for (const key of references) if (props.properties![key].type === 'array') props.properties![key].minItems = 0;
      fields.properties = props;
    }
    definitions[name] = inlineCommon({ type: 'object', properties: fields, required: ['id', 'type', 'title', 'properties', 'content'], additionalProperties: false }) as Schema;
  }
  definitions.PublicNode = { oneOf: Object.keys(definitions).map(name => ({ $ref: `#/$defs/${name}` })) };
  definitions.PublicEdge = {
    type: 'object', properties: {
      source: structuredClone(common.id), field: { type: 'string', pattern: '\\S' }, target: structuredClone(common.id),
    }, required: ['source', 'field', 'target'], additionalProperties: false,
  };
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema', title: 'Public node dataset v1',
    description: 'Generated public projection; see contracts/README.md for graph invariants.',
    type: 'object', properties: {
      schemaVersion: { const: SCHEMA_VERSION }, nodes: { type: 'array', items: { $ref: '#/$defs/PublicNode' } },
      edges: { type: 'array', items: { $ref: '#/$defs/PublicEdge' }, uniqueItems: true },
    }, required: ['schemaVersion', 'nodes', 'edges'], additionalProperties: false, $defs: definitions,
  };
}

function tsType(schema: Schema): string {
  if (schema.$ref) return schema.$ref.split('/').at(-1)!;
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ');
  if (schema.oneOf && !schema.type) return schema.oneOf.map(tsType).join(' | ');
  if (schema.type === 'object') {
    if (!Object.keys(schema.properties ?? {}).length) return schema.additionalProperties === false ? 'Record<string, never>' : 'Record<string, JSONValue>';
    return '{ ' + Object.entries(schema.properties!).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${tsType(value)};`).join(' ') + ' }';
  }
  if (schema.type === 'array') return `Array<${tsType(schema.items!)}>`;
  const type = ({ string: 'string', boolean: 'boolean', integer: 'number', number: 'number', null: 'null' } as Record<string, string>)[schema.type!];
  if (!type) throw new Error(`Unsupported type: ${schema.type}`);
  return type;
}

const header = ['// Generated by seraph-generate-contract. Do not edit.', '// JSON Schema and export validation enforce constraints beyond these types.', ''];

export function generatedContracts(): Record<string, string> {
  const schema = buildPublicSchema();
  const publicTypes = [...header, ...Object.entries(schema.$defs!).map(([name, definition]) => `export type ${name} = ${tsType(definition)};`), `export type PublicDataset = ${tsType(schema)};`];
  const sourceTypes = [...header, 'export type JSONValue = null | boolean | number | string | Array<JSONValue> | { [key: string]: JSONValue };'];
  const common = schemas['common.schema.json'].$defs!.base;
  for (const [name, source] of Object.entries(nodeSchemas)) {
    const definition = inlineCommon({
      type: 'object', properties: { ...common.properties, ...source.properties },
      required: [...(common.required ?? []), ...(source.required ?? [])], additionalProperties: false,
    }) as Schema;
    sourceTypes.push(`export type ${name} = ${tsType(definition)};`);
  }
  sourceTypes.push(`export type NodeRecord = ${Object.keys(nodeSchemas).join(' | ')};`);
  return {
    'public-nodes.schema.json': JSON.stringify(schema, null, 2) + '\n',
    'public-nodes.d.ts': publicTypes.join('\n') + '\n',
    'source-nodes.d.ts': sourceTypes.join('\n') + '\n',
  };
}
